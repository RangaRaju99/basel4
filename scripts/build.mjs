import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const configPath = path.join(projectRoot, "project.config.json");
const sourceRoot = path.join(projectRoot, "src");
const includePattern = /<!--\s*include:\s*([^>]+?)\s*-->/g;

function within(directory, target) {
    const relative = path.relative(directory, target);
    return relative !== ".." && !relative.startsWith(".." + path.sep) && !path.isAbsolute(relative);
}

function sourcePath(reference) {
    if (typeof reference !== "string" || !reference.trim()) {
        throw new Error("An HTML source/include must name a file under src/.");
    }
    const absolute = path.resolve(projectRoot, reference);
    if (!within(sourceRoot, absolute) || absolute === sourceRoot) {
        throw new Error("HTML source/include must stay under src/: " + reference);
    }
    if (!fs.existsSync(absolute) || !fs.statSync(absolute).isFile()) {
        throw new Error("HTML source/include does not exist: " + reference);
    }
    if (!within(fs.realpathSync(sourceRoot), fs.realpathSync(absolute))) {
        throw new Error("HTML source/include resolves outside src/: " + reference);
    }
    return absolute;
}

function expandSource(reference, ancestors = []) {
    const absolute = sourcePath(reference);
    const real = fs.realpathSync(absolute);
    if (ancestors.some(entry => entry.real === real)) {
        const chain = ancestors.map(entry => entry.reference).concat(reference);
        throw new Error("Circular HTML include: " + chain.join(" -> "));
    }
    const chain = ancestors.concat({ real, reference });
    const source = fs.readFileSync(absolute, "utf8");
    return source.replace(includePattern, (_match, included) => {
        try {
            return expandSource(included.trim(), chain);
        } catch (error) {
            throw new Error(reference + ": " + error.message);
        }
    });
}

function readConfig() {
    let config;
    try {
        config = JSON.parse(fs.readFileSync(configPath, "utf8"));
    } catch (error) {
        throw new Error("Cannot read project.config.json: " + error.message);
    }
    if (!Array.isArray(config.pages) || !config.pages.length) {
        throw new Error("project.config.json must contain a nonempty pages array.");
    }
    const outputs = new Set();
    for (const page of config.pages) {
        if (!page || typeof page.source !== "string" || typeof page.output !== "string") {
            throw new Error("Each configured page needs source and output strings.");
        }
        if (!/^[a-zA-Z0-9][a-zA-Z0-9._-]*\.html$/.test(page.output)) {
            throw new Error("Page output must be an HTML filename at the project root: " + page.output);
        }
        if (outputs.has(page.output.toLowerCase())) {
            throw new Error("Duplicate page output: " + page.output);
        }
        outputs.add(page.output.toLowerCase());
    }
    if (config.bundles !== undefined && !Array.isArray(config.bundles)) {
        throw new Error("project.config.json bundles must be an array.");
    }
    for (const bundle of config.bundles || []) {
        if (!bundle || typeof bundle.output !== "string" ||
            !/^assets\/generated\/[a-zA-Z0-9][a-zA-Z0-9._-]*\.js$/.test(bundle.output)) {
            throw new Error("Bundle output must be a JavaScript file under assets/generated/.");
        }
        if (!Array.isArray(bundle.sources) || !bundle.sources.length ||
            bundle.sources.some(source => typeof source !== "string")) {
            throw new Error(bundle.output + ": bundle sources must be a nonempty array of paths.");
        }
        if (["prefix", "suffix"].some(key => bundle[key] !== undefined && typeof bundle[key] !== "string")) {
            throw new Error(bundle.output + ": bundle prefix/suffix must be strings.");
        }
        if (outputs.has(bundle.output.toLowerCase())) {
            throw new Error("Duplicate generated output: " + bundle.output);
        }
        outputs.add(bundle.output.toLowerCase());
    }
    return config;
}

/** Compile pages in memory. Importing this module never writes files. */
export function compilePages() {
    return readConfig().pages.map(page => {
        const expanded = expandSource(page.source);
        const newline = expanded.includes("\r\n") ? "\r\n" : "\n";
        const doctype = /<!doctype\s+html\s*>/i;
        if (!doctype.test(expanded)) {
            throw new Error("Page source must include <!DOCTYPE html>: " + page.source);
        }
        const comment = "<!-- Generated by scripts/build.mjs. Edit " + page.source + " instead. -->";
        return {
            output: page.output,
            content: expanded.replace(doctype, match => match + newline + comment)
        };
    });
}

/** Assemble explicitly ordered scripts without changing their shared scope. */
export function compileBundles() {
    return (readConfig().bundles || []).map(bundle => ({
        output: bundle.output,
        content: "// Generated by scripts/build.mjs. Edit source files listed in project.config.json instead.\n" +
            (bundle.prefix || "") +
            bundle.sources.map(source => fs.readFileSync(sourcePath(source), "utf8")).join("") +
            (bundle.suffix || "")
    }));
}

export function buildPages({ check = false } = {}) {
    const pages = compilePages();
    const bundles = compileBundles();
    const stale = [...pages, ...bundles].filter(page => {
        const output = path.join(projectRoot, page.output);
        return !fs.existsSync(output) || fs.readFileSync(output, "utf8") !== page.content;
    });
    if (check && stale.length) {
        throw new Error("Generated files need rebuilding: " +
            stale.map(page => page.output).join(", ") + ". Run npm run build.");
    }
    if (!check) {
        for (const page of stale) {
            const output = path.join(projectRoot, page.output);
            fs.mkdirSync(path.dirname(output), { recursive: true });
            fs.writeFileSync(output, page.content, "utf8");
        }
    }
    return { pages: pages.length, bundles: bundles.length, updated: check ? 0 : stale.length };
}

function reportBuild() {
    try {
        const result = buildPages();
        console.log("Built " + result.pages + " pages and " + result.bundles + " script bundles (" + result.updated + " updated).");
    } catch (error) {
        console.error("Build failed: " + error.message);
    }
}

function watchSources() {
    reportBuild();
    let timer;
    const schedule = () => {
        clearTimeout(timer);
        timer = setTimeout(reportBuild, 120);
    };
    const watchers = [
        fs.watch(sourceRoot, { recursive: true }, schedule),
        fs.watch(configPath, schedule)
    ];
    for (const watcher of watchers) {
        watcher.on("error", error => {
            console.error("Watch failed: " + error.message);
            process.exitCode = 1;
            watchers.forEach(item => item.close());
        });
    }
    console.log("Watching src/ and project.config.json. Press Ctrl+C to stop.");
    process.once("SIGINT", () => {
        clearTimeout(timer);
        watchers.forEach(watcher => watcher.close());
    });
}

const isEntryPoint = process.argv[1] &&
    path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isEntryPoint) {
    try {
        const args = new Set(process.argv.slice(2));
        const unknown = [...args].filter(arg => arg !== "--check" && arg !== "--watch");
        if (unknown.length || (args.has("--check") && args.has("--watch"))) {
            throw new Error("Usage: node scripts/build.mjs [--check | --watch]");
        }
        if (args.has("--watch")) {
            watchSources();
        } else {
            const result = buildPages({ check: args.has("--check") });
            console.log(args.has("--check")
                ? "Generated files are up to date (" + result.pages + " pages, " + result.bundles + " script bundles)."
                : "Built " + result.pages + " pages and " + result.bundles + " script bundles (" + result.updated + " updated).");
        }
    } catch (error) {
        console.error("Build failed: " + error.message);
        process.exitCode = 1;
    }
}
