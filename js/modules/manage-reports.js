/* =========================================
   MANAGE REPORTS MODULE
   Reads reports generated by Generate Report
========================================= */

(function () {
    "use strict";

    const STORAGE_KEY = "baseltrack-generated-reports";

    let allReports = [];
    let filteredReports = [];
    let currentPage = 1;

    const PAGE_SIZE = 8;

    let toastTimer = null;

    function getElement(id) {
        return document.getElementById(id);
    }

    function escapeHTML(value) {
        return String(value ?? "")
            .replace(/&/g, "&amp;")
            .replace(/</g, "&lt;")
            .replace(/>/g, "&gt;")
            .replace(/"/g, "&quot;")
            .replace(/'/g, "&#039;");
    }

    function readStoredReports() {
        try {
            const stored = JSON.parse(
                localStorage.getItem(STORAGE_KEY) || "[]"
            );

            if (Array.isArray(stored)) {
                return stored;
            }

            if (stored && Array.isArray(stored.reports)) {
                return stored.reports;
            }

            return [];
        } catch (error) {
            console.error("Unable to read generated reports:", error);
            return [];
        }
    }

    function getReportId(report, index) {
        return (
            report.reportId ||
            report.id ||
            report.reference ||
            report.reportReference ||
            report.reportNo ||
            `REPORT-${index + 1}`
        );
    }

    function getReportName(report) {
        return (
            report.reportName ||
            report.name ||
            report.title ||
            report.type ||
            "Consolidated Regulatory Report"
        );
    }

    function getReportBank(report) {
        return (
            report.bank ||
            report.bankName ||
            report.institution ||
            "Multiple Banks"
        );
    }

    function getReportPeriod(report) {
        return (
            report.period ||
            report.reportingPeriod ||
            report.reportPeriod ||
            "-"
        );
    }

    function getReportDate(report) {
        return (
            report.generatedAt ||
            report.createdAt ||
            report.generatedDate ||
            report.date ||
            report.timestamp ||
            ""
        );
    }

    function getReportStatus(report) {
        return report.status || "Generated";
    }

    function getReportRecords(report) {
        const possibleArrays = [
            report.selectedRecords,
            report.records,
            report.calculations,
            report.selectedCalculations,
            report.items,
            report.data
        ];

        for (const value of possibleArrays) {
            if (Array.isArray(value)) {
                return value;
            }
        }

        return [];
    }

    function formatDate(value) {
        if (!value) {
            return "-";
        }

        const date = new Date(value);

        if (Number.isNaN(date.getTime())) {
            return String(value);
        }

        return date.toLocaleDateString("en-IN", {
            day: "2-digit",
            month: "short",
            year: "numeric"
        });
    }

    function statusClass(status) {
        const value = String(status).toLowerCase();

        if (value.includes("approved")) return "approved";
        if (value.includes("completed")) return "completed";
        if (value.includes("generated")) return "generated";
        if (value.includes("pending")) return "pending";
        if (value.includes("review")) return "review";
        if (value.includes("failed")) return "failed";
        if (value.includes("rejected")) return "rejected";

        return "default";
    }

    function showToast(message) {
        const toast = getElement("mrpToast");

        if (!toast) return;

        toast.textContent = message;
        toast.classList.add("show");

        clearTimeout(toastTimer);

        toastTimer = setTimeout(function () {
            toast.classList.remove("show");
        }, 2600);
    }

    function refreshReports() {
        allReports = readStoredReports();

        allReports = allReports.map(function (report, index) {
            return {
                ...report,
                _mrpId: getReportId(report, index),
                _mrpName: getReportName(report),
                _mrpBank: getReportBank(report),
                _mrpPeriod: getReportPeriod(report),
                _mrpDate: getReportDate(report),
                _mrpStatus: getReportStatus(report),
                _mrpRecords: getReportRecords(report)
            };
        });

        applyFilters();
    }

    function updateSummary() {
        const total = allReports.length;

        const approved = allReports.filter(function (report) {
            return String(report._mrpStatus).toLowerCase().includes("approved");
        }).length;

        const pending = allReports.filter(function (report) {
            return String(report._mrpStatus).toLowerCase().includes("pending") ||
                String(report._mrpStatus).toLowerCase().includes("review");
        }).length;

        const records = allReports.reduce(function (sum, report) {
            return sum + report._mrpRecords.length;
        }, 0);

        getElement("mrpTotalReports").textContent = total;
        getElement("mrpApprovedReports").textContent = approved;
        getElement("mrpPendingReports").textContent = pending;
        getElement("mrpCalculationRecords").textContent = records;
    }

    function applyFilters() {
        const search = getElement("mrpSearch").value.trim().toLowerCase();
        const status = getElement("mrpStatusFilter").value;
        const bank = getElement("mrpBankFilter").value;
        const period = getElement("mrpPeriodFilter").value;

        filteredReports = allReports.filter(function (report) {
            const searchableText = [
                report._mrpId,
                report._mrpName,
                report._mrpBank,
                report._mrpPeriod,
                report._mrpStatus
            ].join(" ").toLowerCase();

            const matchesSearch =
                !search || searchableText.includes(search);

            const matchesStatus =
                status === "ALL" ||
                String(report._mrpStatus).toLowerCase() === status.toLowerCase();

            const matchesBank =
                bank === "ALL" ||
                report._mrpBank === bank;

            const matchesPeriod =
                period === "ALL" ||
                report._mrpPeriod === period;

            return matchesSearch &&
                matchesStatus &&
                matchesBank &&
                matchesPeriod;
        });

        currentPage = 1;
        renderTable();
        updateSummary();
    }

    function renderTable() {
        const tbody = getElement("mrpTableBody");

        const total = filteredReports.length;
        const totalPages = Math.max(1, Math.ceil(total / PAGE_SIZE));

        if (currentPage > totalPages) {
            currentPage = totalPages;
        }

        const startIndex = (currentPage - 1) * PAGE_SIZE;
        const pageReports = filteredReports.slice(
            startIndex,
            startIndex + PAGE_SIZE
        );

        getElement("mrpRecordCount").textContent =
            `${total} report${total === 1 ? "" : "s"} found`;

        if (pageReports.length === 0) {
            tbody.innerHTML = `
                <tr>
                    <td colspan="7" class="mrp-empty">
                        <strong>No reports found</strong>
                        ${
                            allReports.length === 0
                                ? "Generate a report first using the Generate Report module."
                                : "Try changing your search or filter criteria."
                        }
                    </td>
                </tr>
            `;

            getElement("mrpPaginationInfo").textContent = "Showing 0 reports";
            getElement("mrpPaginationButtons").innerHTML = "";
            return;
        }

        tbody.innerHTML = pageReports.map(function (report) {
            const status = String(report._mrpStatus);

            return `
                <tr>
                    <td>
                        <span class="mrp-report-name">
                            ${escapeHTML(report._mrpName)}
                        </span>
                        <span class="mrp-report-id">
                            ${escapeHTML(report._mrpId)}
                        </span>
                    </td>

                    <td>${escapeHTML(report._mrpBank)}</td>

                    <td>${escapeHTML(report._mrpPeriod)}</td>

                    <td>${escapeHTML(formatDate(report._mrpDate))}</td>

                    <td>${report._mrpRecords.length}</td>

                    <td>
                        <span class="mrp-status ${statusClass(status)}">
                            ${escapeHTML(status)}
                        </span>
                    </td>

                    <td>
                        <div class="mrp-action-group">
                            <button
                                type="button"
                                class="mrp-action-btn"
                                data-mrp-action="view"
                                data-mrp-id="${escapeHTML(report._mrpId)}"
                            >
                                View
                            </button>

                            <button
                                type="button"
                                class="mrp-action-btn"
                                data-mrp-action="export"
                                data-mrp-id="${escapeHTML(report._mrpId)}"
                            >
                                Export CSV
                            </button>

                            <button
                                type="button"
                                class="mrp-action-btn"
                                data-mrp-action="print"
                                data-mrp-id="${escapeHTML(report._mrpId)}"
                            >
                                Print
                            </button>
                        </div>
                    </td>
                </tr>
            `;
        }).join("");

        const first = startIndex + 1;
        const last = Math.min(startIndex + PAGE_SIZE, total);

        getElement("mrpPaginationInfo").textContent =
            `Showing ${first}-${last} of ${total} reports`;

        renderPagination(totalPages);
    }

    function renderPagination(totalPages) {
        const container = getElement("mrpPaginationButtons");

        let html = `
            <button class="mrp-btn"
                type="button"
                data-mrp-page="${currentPage - 1}"
                ${currentPage === 1 ? "disabled" : ""}>
                Previous
            </button>
        `;

        for (let page = 1; page <= totalPages; page++) {
            html += `
                <button
                    class="mrp-btn ${page === currentPage ? "mrp-btn-primary" : ""}"
                    type="button"
                    data-mrp-page="${page}">
                    ${page}
                </button>
            `;
        }

        html += `
            <button class="mrp-btn"
                type="button"
                data-mrp-page="${currentPage + 1}"
                ${currentPage === totalPages ? "disabled" : ""}>
                Next
            </button>
        `;

        container.innerHTML = html;
    }

    function findReport(reportId) {
        return allReports.find(function (report) {
            return String(report._mrpId) === String(reportId);
        });
    }

    function openReport(reportId) {
        const report = findReport(reportId);

        if (!report) {
            showToast("Report could not be found.");
            return;
        }

        const records = report._mrpRecords;

        const detailRows = records.length
            ? records.map(function (record, index) {
                const calculationId =
                    record.calculationId ||
                    record.id ||
                    record.reference ||
                    `Record ${index + 1}`;

                const type =
                    record.type ||
                    record.calculationType ||
                    record.reportType ||
                    "-";

                const bank =
                    record.bank ||
                    record.bankName ||
                    "-";

                const period =
                    record.period ||
                    record.reportingPeriod ||
                    "-";

                const result =
                    record.primaryResult ??
                    record.result ??
                    record.value ??
                    "-";

                return `
                    <tr>
                        <td>${escapeHTML(calculationId)}</td>
                        <td>${escapeHTML(type)}</td>
                        <td>${escapeHTML(bank)}</td>
                        <td>${escapeHTML(period)}</td>
                        <td>${escapeHTML(result)}</td>
                    </tr>
                `;
            }).join("")
            : `
                <tr>
                    <td colspan="5" class="mrp-empty">
                        No calculation details are available for this report.
                    </td>
                </tr>
            `;

        getElement("mrpModalContent").innerHTML = `
            <div class="mrp-detail-grid">
                <div class="mrp-detail-item">
                    <span>Report ID</span>
                    <strong>${escapeHTML(report._mrpId)}</strong>
                </div>

                <div class="mrp-detail-item">
                    <span>Report Name</span>
                    <strong>${escapeHTML(report._mrpName)}</strong>
                </div>

                <div class="mrp-detail-item">
                    <span>Bank</span>
                    <strong>${escapeHTML(report._mrpBank)}</strong>
                </div>

                <div class="mrp-detail-item">
                    <span>Reporting Period</span>
                    <strong>${escapeHTML(report._mrpPeriod)}</strong>
                </div>

                <div class="mrp-detail-item">
                    <span>Generated Date</span>
                    <strong>${escapeHTML(formatDate(report._mrpDate))}</strong>
                </div>

                <div class="mrp-detail-item">
                    <span>Status</span>
                    <strong>${escapeHTML(report._mrpStatus)}</strong>
                </div>
            </div>

            <h4>Included Calculation Records</h4>

            <div class="mrp-table-wrap">
                <table class="mrp-table">
                    <thead>
                        <tr>
                            <th>Calculation ID</th>
                            <th>Type</th>
                            <th>Bank</th>
                            <th>Period</th>
                            <th>Result</th>
                        </tr>
                    </thead>
                    <tbody>
                        ${detailRows}
                    </tbody>
                </table>
            </div>
        `;

        getElement("mrpModal").classList.add("show");
    }

    function closeModal() {
        getElement("mrpModal").classList.remove("show");
    }

    function downloadCSV(reportId) {
        const report = findReport(reportId);

        if (!report) {
            showToast("Report could not be found.");
            return;
        }

        const rows = [
            ["Report ID", report._mrpId],
            ["Report Name", report._mrpName],
            ["Bank", report._mrpBank],
            ["Reporting Period", report._mrpPeriod],
            ["Generated Date", formatDate(report._mrpDate)],
            ["Status", report._mrpStatus],
            [],
            [
                "Calculation ID",
                "Type",
                "Bank",
                "Period",
                "Business Date",
                "Primary Result"
            ]
        ];

        report._mrpRecords.forEach(function (record, index) {
            rows.push([
                record.calculationId || record.id || `Record ${index + 1}`,
                record.type || record.calculationType || record.reportType || "",
                record.bank || record.bankName || "",
                record.period || record.reportingPeriod || "",
                record.businessDate || record.date || "",
                record.primaryResult ?? record.result ?? record.value ?? ""
            ]);
        });

        const csv = rows.map(function (row) {
            return row.map(function (cell) {
                const value = String(cell ?? "").replace(/"/g, '""');
                return `"${value}"`;
            }).join(",");
        }).join("\r\n");

        const blob = new Blob(
            ["\uFEFF" + csv],
            { type: "text/csv;charset=utf-8;" }
        );

        const url = URL.createObjectURL(blob);
        const link = document.createElement("a");

        link.href = url;
        link.download = `${report._mrpId}.csv`;

        document.body.appendChild(link);
        link.click();
        link.remove();

        URL.revokeObjectURL(url);

        showToast("Report exported as CSV.");
    }

    function printReport(reportId) {
        const report = findReport(reportId);

        if (!report) {
            showToast("Report could not be found.");
            return;
        }

        const rows = report._mrpRecords.map(function (record, index) {
            return `
                <tr>
                    <td>${escapeHTML(
                        record.calculationId ||
                        record.id ||
                        `Record ${index + 1}`
                    )}</td>
                    <td>${escapeHTML(
                        record.type ||
                        record.calculationType ||
                        record.reportType ||
                        "-"
                    )}</td>
                    <td>${escapeHTML(
                        record.bank ||
                        record.bankName ||
                        "-"
                    )}</td>
                    <td>${escapeHTML(
                        record.period ||
                        record.reportingPeriod ||
                        "-"
                    )}</td>
                    <td>${escapeHTML(
                        record.primaryResult ??
                        record.result ??
                        record.value ??
                        "-"
                    )}</td>
                </tr>
            `;
        }).join("");

        const printWindow = window.open("", "_blank");

        if (!printWindow) {
            showToast("Allow pop-ups to print this report.");
            return;
        }

        printWindow.document.write(`
            <!DOCTYPE html>
            <html>
            <head>
                <title>${escapeHTML(report._mrpId)}</title>
                <style>
                    body {
                        font-family: Arial, sans-serif;
                        padding: 30px;
                        color: #23332c;
                    }

                    h1 {
                        color: #167a58;
                        margin-bottom: 5px;
                    }

                    .meta {
                        margin: 20px 0;
                        line-height: 1.8;
                    }

                    table {
                        width: 100%;
                        border-collapse: collapse;
                        margin-top: 20px;
                    }

                    th, td {
                        border: 1px solid #dce5df;
                        padding: 10px;
                        text-align: left;
                        font-size: 12px;
                    }

                    th {
                        background: #edf5f0;
                    }

                    @media print {
                        button {
                            display: none;
                        }
                    }
                </style>
            </head>
            <body>
                <h1>BaselTrack</h1>
                <h2>${escapeHTML(report._mrpName)}</h2>

                <div class="meta">
                    <strong>Report ID:</strong> ${escapeHTML(report._mrpId)}<br>
                    <strong>Bank:</strong> ${escapeHTML(report._mrpBank)}<br>
                    <strong>Reporting Period:</strong> ${escapeHTML(report._mrpPeriod)}<br>
                    <strong>Generated Date:</strong> ${escapeHTML(formatDate(report._mrpDate))}<br>
                    <strong>Status:</strong> ${escapeHTML(report._mrpStatus)}
                </div>

                <h3>Included Calculation Records</h3>

                <table>
                    <thead>
                        <tr>
                            <th>Calculation ID</th>
                            <th>Type</th>
                            <th>Bank</th>
                            <th>Period</th>
                            <th>Result</th>
                        </tr>
                    </thead>
                    <tbody>${rows}</tbody>
                </table>

                <br>
                <button onclick="window.print()">Print / Save as PDF</button>
            </body>
            </html>
        `);

        printWindow.document.close();
    }

    function resetFilters() {
        getElement("mrpSearch").value = "";
        getElement("mrpStatusFilter").value = "ALL";
        getElement("mrpBankFilter").value = "ALL";
        getElement("mrpPeriodFilter").value = "ALL";

        applyFilters();
    }

    function bindEvents() {
        const root = getElement("manageReportsApp");

        if (!root || root.dataset.initialized === "true") {
            return;
        }

        root.dataset.initialized = "true";

        root.addEventListener("click", function (event) {
            const actionButton = event.target.closest("[data-mrp-action]");

            if (actionButton) {
                const action = actionButton.dataset.mrpAction;
                const reportId = actionButton.dataset.mrpId;

                if (action === "view") openReport(reportId);
                if (action === "export") downloadCSV(reportId);
                if (action === "print") printReport(reportId);

                return;
            }

            const pageButton = event.target.closest("[data-mrp-page]");

            if (pageButton && !pageButton.disabled) {
                currentPage = Number(pageButton.dataset.mrpPage);
                renderTable();
                return;
            }

            if (event.target.closest("#mrpRefresh")) {
                refreshReports();
                showToast("Report list refreshed.");
                return;
            }

            if (event.target.closest("#mrpReset")) {
                resetFilters();
                return;
            }

            if (event.target.closest("#mrpApply")) {
                applyFilters();
                return;
            }

            if (event.target.closest("[data-mrp-close]")) {
                closeModal();
            }
        });

        getElement("mrpModal").addEventListener("click", function (event) {
            if (event.target.id === "mrpModal") {
                closeModal();
            }
        });

        getElement("mrpSearch").addEventListener("input", applyFilters);
    }

    window.initManageReportsModule = function () {
        const root = getElement("manageReportsApp");

        if (!root) {
            console.error("Manage Reports template was not found.");
            return;
        }

        bindEvents();
        refreshReports();
    };

})();